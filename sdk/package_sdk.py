#!/usr/bin/env python3
"""Build or verify a source SDK ZIP with a SHA-256 inventory; stdlib only."""

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import zipfile


ROOT = Path(__file__).resolve().parent.parent
FIXED_FILES = (
    "README.md", "CMakeLists.txt", ".gitignore", ".eide/eide.yml",
    "wheel_rail.ioc", "wheel_rail.code-workspace", "Core/Src/main.c",
)
PATTERNS = (
    "src/**/*.c", "src/**/*.h", "sdk/**/*.c", "sdk/**/*.h",
    "sdk/**/*.py", "sdk/**/CMakeLists.txt", "cmake/*.cmake.in", "tests/*.c",
)


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def verify(path):
    with zipfile.ZipFile(path) as archive:
        names = archive.namelist()
        if len(names) != len(set(names)):
            raise ValueError("Duplicate archive entries")
        for name in names:
            parts = PurePosixPath(name).parts
            if name.startswith("/") or ".." in parts or "\\" in name or ":" in name:
                raise ValueError(f"Unsafe archive path: {name}")
        manifests = [name for name in names if name.endswith("/SDK_MANIFEST.json")]
        if len(manifests) != 1:
            raise ValueError("Expected exactly one SDK_MANIFEST.json")
        manifest = json.loads(archive.read(manifests[0]))
        prefix = manifests[0].removesuffix("SDK_MANIFEST.json")
        expected = {prefix + name for name in manifest["files"]} | {manifests[0]}
        if set(names) != expected:
            raise ValueError("Archive contents differ from the manifest")
        for name, expected_hash in manifest["files"].items():
            if sha256(archive.read(prefix + name)) != expected_hash:
                raise ValueError(f"SHA-256 mismatch: {name}")
        readmes = [name for name in manifest["files"] if Path(name).name.lower() == "readme.md"]
        if readmes != ["README.md"]:
            raise ValueError("Expected one root SDK README")
        return manifest


def package(output):
    header = (ROOT / "sdk/wheel_rail_sdk.h").read_text(encoding="utf-8")
    match = re.search(r'#define WHEEL_RAIL_SDK_VERSION "([0-9]+\.[0-9]+\.[0-9]+)"', header)
    if not match:
        raise ValueError("Missing SDK version macro")
    version = match.group(1)
    name = f"wheel-rail-sdk-{version}-source"
    paths = {ROOT / item for item in FIXED_FILES}
    for pattern in PATTERNS:
        paths.update(ROOT.glob(pattern))
    contents = {}
    for path in sorted(paths):
        if not path.is_file() or path.is_symlink() or ROOT not in path.resolve().parents:
            raise ValueError(f"Missing or invalid SDK input: {path}")
        contents[path.relative_to(ROOT).as_posix()] = path.read_bytes()
    manifest = {
        "format_version": 1,
        "sdk_version": version,
        "delivery": "source",
        "platform": "STM32H723VGT6 reference adapter; HAL generated by host",
        "files": {key: sha256(data) for key, data in sorted(contents.items())},
    }
    contents["SDK_MANIFEST.json"] = (json.dumps(manifest, indent=2, ensure_ascii=False) + "\n").encode("utf-8")
    output = Path(output) if output else ROOT / "build/dist" / (name + ".zip")
    output = output.resolve()
    if output in paths:
        raise ValueError("Output cannot overwrite an SDK input file")
    output.parent.mkdir(parents=True, exist_ok=True)
    # Stable entry order and timestamps keep identical inputs reproducible.
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for relative, data in sorted(contents.items()):
            info = zipfile.ZipInfo(f"{name}/{relative}", date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o100644 << 16
            archive.writestr(info, data)
    verify(output)
    return output, manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--output", type=Path, help="Output ZIP (default: build/dist/<version>.zip)")
    mode.add_argument("--verify", type=Path, help="Verify an existing SDK source ZIP")
    args = parser.parse_args()
    try:
        if args.verify:
            output, manifest = args.verify.resolve(), verify(args.verify)
        else:
            output, manifest = package(args.output)
    except (OSError, ValueError, KeyError, zipfile.BadZipFile) as error:
        parser.exit(1, f"SDK package error: {error}\n")
    print(json.dumps({"path": str(output), "version": manifest["sdk_version"],
                      "source_files": len(manifest["files"]),
                      "archive_sha256": sha256(output.read_bytes()), "verified": True},
                     ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
